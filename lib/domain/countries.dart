/// Every country the phone picker offers — generated from the web's
/// `lib/country-data.ts` (`ALL_COUNTRIES`) so both apps list the same
/// countries under the same names. [kCommonCountryCount] are the East
/// African and expat-origin countries the web lists first.
library;

class Country {
  const Country(this.name, this.iso, this.dialCode);
  final String name;

  /// ISO 3166-1 alpha-2, e.g. `TZ`.
  final String iso;

  /// `+255`, `+1` …
  final String dialCode;

  /// The flag emoji, built from the ISO code's regional indicators.
  String get flag => String.fromCharCodes(
      iso.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 0x41));
}

